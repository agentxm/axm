import { createHash } from "node:crypto";
import * as Data from "effect/Data";
import * as Effect from "effect/Effect";
import * as FileSystem from "effect/FileSystem";
import * as Path from "effect/Path";
import * as Schema from "effect/Schema";
import { parse as parseYaml } from "yaml";

const GLOSSARY_SOURCE = "knowledge/agent-extension-engineering/src/glossary.md";
const GLOSSARY_OUTPUTS = [
  "apps/cli/help/topics/glossary.md",
  "skills/axm/src/references/glossary.md",
  "apps/cli/site-content/__generated__/agent-extension-glossary.md",
] as const;

const manifestSchema = Schema.Struct({
  owner: Schema.Literal("@agentxm"),
  name: Schema.Literal("agent-extension-engineering"),
  version: Schema.String,
  license: Schema.Literal("CC-BY-4.0"),
});

const conceptSchema = Schema.Struct({
  type: Schema.Literal("Reference"),
  title: Schema.String,
  description: Schema.String,
});

class GlossarySourceError extends Data.TaggedError("GlossarySourceError")<{
  readonly message: string;
}> {}

/** Copies the complete concept body; no second authored vocabulary or term selector. */
export const renderGlossary = (source: string, manifest: unknown) =>
  Effect.gen(function* () {
    const identity = yield* Schema.decodeUnknownEffect(manifestSchema)(manifest);
    const frontmatter = /^---\r?\n([\s\S]*?)\r?\n---\r?\n/u.exec(source);
    if (frontmatter === null)
      return yield* new GlossarySourceError({ message: "Glossary requires OKF frontmatter" });
    const metadata: unknown = yield* Effect.try(() => parseYaml(frontmatter[1] ?? ""));
    const concept = yield* Schema.decodeUnknownEffect(conceptSchema)(metadata);
    const body = source.slice(frontmatter[0].length).trim();
    if (!body.startsWith(`# ${concept.title}\n`))
      return yield* new GlossarySourceError({ message: "Glossary title must match its heading" });
    // Copies travel independently: fragments and HTTPS links work in every destination.
    const links = [...body.matchAll(/\]\(([^\s)]+)(?:\s+[^)]*)?\)/gu)];
    const nonPortable = links.find((match) => {
      const target = match[1] ?? "";
      return !target.startsWith("#") && !target.startsWith("https://");
    });
    if (nonPortable !== undefined)
      return yield* new GlossarySourceError({
        message: `Non-portable glossary link: ${nonPortable[1]}`,
      });
    const digest = createHash("sha256").update(source).digest("hex");
    const snapshot = `@agentxm/knowledge/${identity.name}@${identity.version}#glossary`;
    // An unused Markdown link definition retains provenance without rendering
    // metadata in website readers that escape HTML. Raw readers see it last.
    const provenance = `[axm-glossary-source]: https://github.com/agentxm/axm/blob/main/${GLOSSARY_SOURCE} "Generated by cli:generate:glossary; Snapshot: ${snapshot}; Source SHA-256: ${digest}"`;
    const attribution = `Source: [Agent Extension Glossary](https://github.com/agentxm/axm/blob/main/${GLOSSARY_SOURCE}), ${identity.owner}, [${identity.license}](https://creativecommons.org/licenses/by/4.0/). Snapshot: \`${snapshot}\`.`;
    return `${body}\n\n---\n\n${attribution}\n\n${provenance}\n`;
  });

export const generateGlossary = (root: string) =>
  Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;
    const source = yield* fs.readFileString(path.join(root, GLOSSARY_SOURCE));
    const manifestRaw = yield* fs.readFileString(
      path.join(root, "knowledge/agent-extension-engineering/knowledge.json"),
    );
    const manifest: unknown = yield* Effect.try(() => JSON.parse(manifestRaw));
    const rendered = yield* renderGlossary(source, manifest);
    for (const output of GLOSSARY_OUTPUTS) {
      const target = path.join(root, output);
      yield* fs.makeDirectory(path.dirname(target), { recursive: true });
      yield* fs.writeFileString(target, rendered);
    }
  });
