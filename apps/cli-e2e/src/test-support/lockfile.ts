/**
 * Local reader and editor for the `axm.lock` document the built CLI writes.
 *
 * An end-to-end project observes only shipped artifacts, so it may not import
 * the application's lockfile codec. This decoder declares the TOML data model
 * the examples read: one `[[package]]` record per retained package, alias-keyed
 * binding tables that point at a record `id`, and `[[mcp]]` rows.
 */

import * as fs from "node:fs";
import * as path from "node:path";
import * as Schema from "effect/Schema";
import { parse, stringify } from "smol-toml";

/** The workspace lockfile's file name. */
export const LOCKFILE_NAME = "axm.lock";

/** The superseded YAML lockfile the CLI refuses beside `axm.lock`. */
export const LEGACY_LOCKFILE_NAME = "axm-lock.yaml";

/** The supported lockfile format version. */
export const LOCKFILE_VERSION = 1;

/** The canonical bytes of a lockfile with no packages, bindings, or projections. */
export const EMPTY_LOCKFILE = [
  "#:schema https://axm.sh/schemas/axm-lock.schema.json",
  "# Generated by axm; do not edit by hand. See: axm help workspace-state",
  "version = 1",
  "",
].join("\n");

/** The lockfile path of the workspace rooted at `root`. */
export const lockfilePath = (root: string): string => path.join(root, LOCKFILE_NAME);

const LockBinding = Schema.Struct({
  package: Schema.String,
  name: Schema.String,
  spec: Schema.optional(Schema.String),
  component: Schema.optional(Schema.Record(Schema.String, Schema.Unknown)),
});

/** One alias-keyed binding (or `[[mcp]]` row) naming a retained package record. */
export type LockBinding = typeof LockBinding.Type;

const LockPackage = Schema.Struct({
  id: Schema.String,
  source: Schema.Record(Schema.String, Schema.Unknown),
  version: Schema.optional(Schema.String),
  archive: Schema.optional(Schema.String),
  publisher: Schema.optional(Schema.String),
  commit: Schema.optional(Schema.String),
  "git-tree": Schema.optional(Schema.String),
  artifact: Schema.optional(Schema.Record(Schema.String, Schema.Unknown)),
  tree: Schema.String,
  "manifest-version": Schema.optional(Schema.String),
  "manifest-identity": Schema.optional(Schema.String),
  "source-root": Schema.optional(Schema.String),
  dependencies: Schema.optional(Schema.Array(Schema.Record(Schema.String, Schema.String))),
});

/** One `[[package]]` record: a retained package's source and accepted snapshot. */
export type LockPackage = typeof LockPackage.Type;

const Bindings = Schema.optional(Schema.Record(Schema.String, LockBinding));

const LockDocument = Schema.Struct({
  version: Schema.Number,
  package: Schema.optional(Schema.Array(LockPackage)),
  skills: Bindings,
  subagents: Bindings,
  rules: Bindings,
  hooks: Bindings,
  knowledge: Bindings,
  packs: Bindings,
  mcp: Schema.optional(Schema.Array(LockBinding)),
  projections: Schema.optional(Schema.Record(Schema.String, Schema.Unknown)),
  tool: Schema.optional(Schema.Record(Schema.String, Schema.Unknown)),
});

/** The decoded `axm.lock` document. */
export type LockDocument = typeof LockDocument.Type;

/** An alias-keyed binding table of the lockfile. */
export type LockBindingTable = "skills" | "subagents" | "rules" | "hooks" | "knowledge" | "packs";

const decodeLockDocument = Schema.decodeUnknownSync(LockDocument);

/**
 * Parse lockfile text as TOML and decode it. Unknown keys are refused, so an
 * assertion that a field is absent observes the file rather than the decoder.
 */
export const parseLockfile = (text: string): LockDocument =>
  decodeLockDocument(parse(text), { onExcessProperty: "error" });

/** Read and decode the lockfile at `file`. */
export const readLockfile = (file: string): LockDocument =>
  parseLockfile(fs.readFileSync(file, "utf8"));

/** The retained package record whose `id` is `id`; fails when there is none. */
export const lockPackage = (lock: LockDocument, id: string): LockPackage => {
  const record = lock.package?.find((candidate) => candidate.id === id);
  if (record === undefined) throw new Error(`Expected a retained package record ${id}`);
  return record;
};

/** The retained package record a binding points at; fails when the binding is absent. */
export const boundPackage = (
  lock: LockDocument,
  table: LockBindingTable,
  alias: string,
): LockPackage => {
  const binding = lock[table]?.[alias];
  if (binding === undefined) throw new Error(`Expected a ${table} binding for ${alias}`);
  return lockPackage(lock, binding.package);
};

const isRecord = (value: unknown): value is Record<string, unknown> =>
  typeof value === "object" && value !== null && !Array.isArray(value);

const referencedPackageIds = (document: Record<string, unknown>): ReadonlySet<string> => {
  const ids = new Set<string>();
  const add = (binding: unknown) => {
    if (isRecord(binding) && typeof binding["package"] === "string") ids.add(binding["package"]);
  };
  for (const table of ["skills", "subagents", "rules", "hooks", "knowledge", "packs"]) {
    const bindings = document[table];
    if (isRecord(bindings)) Object.values(bindings).forEach(add);
  }
  const mcp = document["mcp"];
  if (Array.isArray(mcp)) mcp.forEach(add);
  return ids;
};

/**
 * Hand-withdraw one binding from the lockfile at `file`, together with any
 * retained package record no remaining binding references, so the edited file
 * stays a valid lockfile. Every other key is kept as parsed.
 */
export const withdrawLockBinding = (file: string, table: LockBindingTable, alias: string): void => {
  const document = parse(fs.readFileSync(file, "utf8"));
  const bindings = document[table];
  if (isRecord(bindings)) {
    delete bindings[alias];
    if (Object.keys(bindings).length === 0) delete document[table];
  }
  const records = document["package"];
  if (Array.isArray(records)) {
    const referenced = referencedPackageIds(document);
    const retained = records.filter(
      (record) =>
        isRecord(record) && typeof record["id"] === "string" && referenced.has(record["id"]),
    );
    if (retained.length === 0) delete document["package"];
    else document["package"] = retained;
  }
  fs.writeFileSync(file, stringify(document));
};
