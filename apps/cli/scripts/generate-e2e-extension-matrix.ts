/**
 * Generate the cli-e2e extension-type matrix from the canonical type table.
 *
 * apps/cli-e2e may depend only on tooling and contract libraries (the
 * `role:e2e` module-boundary rule in eslint.config.mjs), so it cannot import
 * the workspace-kernel agent policy it needs to drive a per-type suite. The CLI
 * already composes both sources, so it owns the copy: emitting plain literals
 * into the e2e package keeps the suite catalog-driven — a new extension type
 * shows up as a new row — without adding an edge to the graph.
 */

// Runs under `bun --conditions=axm-source`, so every workspace package import
// resolves to source and the emitted matrix cannot drift behind stale dist output.
// @effect-diagnostics nodeBuiltinImport:off globalConsole:off — build-time generation script, not Effect code
import * as fs from "node:fs";
import * as path from "node:path";
import { format as formatWithPrettier, resolveConfig as resolvePrettierConfig } from "prettier";

import {
  EXTENSION_TYPE_TABLE,
  extensionTypes,
} from "@agentxm/extension-model/unstable/extensions/common";
import { EXTENSION_CONFIGURED_AGENT_POLICY } from "@agentxm/workspace-kernel/agent-adapters";

const PROJECT_ROOT = path.join(import.meta.dirname, "..");
const OUTPUT_PATH = path.join(
  PROJECT_ROOT,
  "../cli-e2e/src/__generated__/extension-type-matrix.ts",
);

// Publishability is not emitted: each e2e suite carries its own total record of
// per-type publishers keyed by the emitted type union.
const rowEntries = extensionTypes
  .map((type) => {
    const row = EXTENSION_TYPE_TABLE[type];
    // Container types update every configured member; the others select one by name.
    const updateSelection = row.placement === "container" ? "all" : "name-filter";
    return `  {
    type: ${JSON.stringify(type)},
    plural: ${JSON.stringify(row.plural)},
    label: ${JSON.stringify(row.label)},
    sentenceLabel: ${JSON.stringify(row.sentenceLabel)},
    workspaceCapability: ${JSON.stringify(row.workspaceCapability)},
    updateSelection: ${JSON.stringify(updateSelection)},
    configuredAgentPolicy: ${JSON.stringify(EXTENSION_CONFIGURED_AGENT_POLICY[type].kind)},
  },`;
  })
  .join("\n");

const source = `/**
 * @generated by cli:generate:e2e-extension-matrix (apps/cli/scripts/generate-e2e-extension-matrix.ts)
 * Source:     EXTENSION_TYPE_TABLE in packages/core/extension-model and EXTENSION_CONFIGURED_AGENT_POLICY in packages/core/workspace-kernel
 * Regenerate: pnpm exec nx run cli:generate:e2e-extension-matrix
 * DO NOT EDIT - changes are overwritten on regeneration.
 *
 * Plain literals on purpose: apps/cli-e2e must not depend on
 * the product library packages, so the type table is copied in rather than imported.
 */

export const EXTENSION_TYPE_MATRIX = [
${rowEntries}
] as const;

export type ExtensionTypeMatrixRow = (typeof EXTENSION_TYPE_MATRIX)[number];

export type MatrixExtensionType = ExtensionTypeMatrixRow["type"];
`;

fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });

const prettierConfig = (await resolvePrettierConfig(OUTPUT_PATH)) ?? {};
const formatted = await formatWithPrettier(source, {
  ...prettierConfig,
  filepath: OUTPUT_PATH,
  parser: "typescript",
});

fs.writeFileSync(OUTPUT_PATH, formatted);
console.log(`Generated: ${path.relative(PROJECT_ROOT, OUTPUT_PATH)}`);
