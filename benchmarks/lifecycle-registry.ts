/** Loopback Registry backed by the deterministic file Registry fixture. */

import * as fs from "node:fs";
import * as http from "node:http";
import * as path from "node:path";
import { createHash } from "node:crypto";
import * as Effect from "effect/Effect";
import * as Data from "effect/Data";
import * as Schema from "effect/Schema";

interface RequestRecord {
  readonly key: string;
  readonly status: number;
  readonly responseBytes: number;
  readonly archiveBody: boolean;
}

export interface RequestMetrics {
  readonly requests: number;
  readonly uniqueKeys: number;
  readonly repeatedKeys: number;
  readonly retryAttempts: number;
  readonly archiveBodies: number;
  readonly archiveBytes: number;
  readonly peakActiveArchiveBodies: number;
  readonly byStatus: Readonly<Record<string, number>>;
}

export interface LifecycleRegistry {
  readonly url: string;
  readonly reset: (record: boolean) => void;
  readonly failNextMetadata: (name: string) => void;
  readonly metrics: () => RequestMetrics | null;
  readonly close: () => Promise<void>;
}

const isRecord = (value: unknown): value is Record<string, unknown> =>
  typeof value === "object" && value !== null && !Array.isArray(value);

// This fixture serves only the skill/pack identities generated by lifecycle.ts.
const MetadataRequestSchema = Schema.Struct({
  schemaVersion: Schema.Literal(1),
  selectionPolicyVersion: Schema.Literal("1"),
  items: Schema.Array(
    Schema.Struct({
      key: Schema.String,
      identity: Schema.Struct({
        owner: Schema.Literal("@acme"),
        type: Schema.Literals(["skill", "pack"]),
        name: Schema.String.check(Schema.isPattern(/^bench-(?:\d{3}|pack-[ab])$/)),
      }),
      purpose: Schema.Literals(["select", "restore-exact"]),
      expectedPublisherBinding: Schema.optional(Schema.String),
      knownRevision: Schema.optional(Schema.String),
      accepted: Schema.optional(
        Schema.Struct({ version: Schema.String, integrity: Schema.String }),
      ),
    }),
  ).check(Schema.isMinLength(1), Schema.isMaxLength(100)),
});

class MetadataRequestFailed extends Data.TaggedError("MetadataRequestFailed")<{
  readonly cause: unknown;
}> {}

const readMetadataRequest = (request: http.IncomingMessage) =>
  Effect.tryPromise({
    try: async () => {
      const chunks: Buffer[] = [];
      let bytes = 0;
      for await (const chunk of request) {
        if (!Buffer.isBuffer(chunk)) throw new Error("Invalid request body chunk.");
        bytes += chunk.byteLength;
        if (bytes > 256 * 1024) throw new Error("Benchmark metadata request is too large.");
        chunks.push(chunk);
      }
      return Schema.decodeUnknownSync(Schema.fromJsonString(MetadataRequestSchema))(
        Buffer.concat(chunks).toString("utf8"),
      );
    },
    catch: (cause) => new MetadataRequestFailed({ cause }),
  });

const indexBody = (file: string): unknown => {
  const parsed: unknown = JSON.parse(fs.readFileSync(file, "utf8"));
  if (!isRecord(parsed) || !Array.isArray(parsed["versions"])) {
    throw new Error("Invalid benchmark Registry index.");
  }
  return {
    owner: parsed["owner"],
    type: parsed["type"],
    name: parsed["name"],
    publisher_binding_id: parsed["publisherBindingId"],
    visibility: "public",
    archival: parsed["archival"],
    deprecation: parsed["deprecation"],
    versions: parsed["versions"],
  };
};

export const startLifecycleRegistry = async (
  fixtureRoot: string,
  archiveBodyDelayMs: number,
): Promise<LifecycleRegistry> => {
  let recording = false;
  let records: Array<RequestRecord> = [];
  let activeArchiveBodies = 0;
  let peakActiveArchiveBodies = 0;
  const failNextMetadata = new Set<string>();
  const server = http.createServer((request, response) => {
    const url = new URL(request.url ?? "/", "http://benchmark.test");
    const segments = url.pathname.split("/").filter(Boolean).map(decodeURIComponent);
    const method = request.method ?? "UNKNOWN";
    let requestKey = `${method} ${url.pathname}`;
    const finish = (status: number, bytes: number, archiveBody: boolean): void => {
      if (recording) {
        records.push({
          key: requestKey,
          status,
          responseBytes: bytes,
          archiveBody,
        });
      }
    };
    const send = (
      status: number,
      body: string | Buffer,
      contentType: string,
      archiveBody = false,
    ) => {
      const byteLength = Buffer.byteLength(body);
      if (archiveBody && method === "GET") {
        activeArchiveBodies += 1;
        peakActiveArchiveBodies = Math.max(peakActiveArchiveBodies, activeArchiveBodies);
      }
      response.once("finish", () => {
        if (archiveBody && method === "GET") activeArchiveBodies -= 1;
        finish(status, method === "HEAD" ? 0 : byteLength, archiveBody && method === "GET");
      });
      response.writeHead(status, {
        "content-type": contentType,
        "content-length": String(byteLength),
      });
      if (archiveBody && method === "GET" && archiveBodyDelayMs > 0) {
        setTimeout(() => response.end(body), archiveBodyDelayMs);
      } else {
        response.end(method === "HEAD" ? undefined : body);
      }
    };
    const sendProblem = (status: number, title: string, code: string): void => {
      send(
        status,
        JSON.stringify({ type: "about:blank", title, status, detail: title, code }),
        "application/problem+json",
      );
    };
    if (method === "POST" && url.pathname === "/v1/resolutions/metadata") {
      void Effect.runPromise(readMetadataRequest(request))
        .then((body) => {
          // Different batches share a route, but are not duplicate requests.
          requestKey += ` ${JSON.stringify(body)}`;
          if (body.items.some((item) => failNextMetadata.delete(item.identity.name))) {
            send(
              503,
              JSON.stringify({ code: "backend-unavailable", detail: "Temporary fixture failure" }),
              "application/json",
            );
            return;
          }
          const observedAt = new Date().toISOString();
          const results = body.items.map((item) => {
            const plural = item.identity.type === "skill" ? "skills" : "packs";
            const indexPath = path.join(
              fixtureRoot,
              "extensions",
              item.identity.owner,
              plural,
              item.identity.name,
              "index.json",
            );
            if (!fs.existsSync(indexPath)) return { key: item.key, outcome: "unavailable" };
            const index = indexBody(indexPath);
            if (!isRecord(index) || !Array.isArray(index["versions"]))
              throw new Error("Invalid fixture index.");
            const publisherBindingId = index["publisher_binding_id"];
            if (
              item.expectedPublisherBinding !== undefined &&
              item.expectedPublisherBinding !== publisherBindingId
            ) {
              return { key: item.key, outcome: "binding-conflict", publisherBindingId };
            }
            if (item.purpose === "restore-exact") {
              const accepted = item.accepted;
              const exact = index["versions"].find(
                (version: unknown) => isRecord(version) && version["version"] === accepted?.version,
              );
              if (!isRecord(exact))
                return { key: item.key, outcome: "exact-conflict", reason: "version-unavailable" };
              if (exact["integrity"] !== accepted?.integrity)
                return { key: item.key, outcome: "exact-conflict", reason: "integrity-mismatch" };
            }
            if (index["versions"].length > 100)
              throw new Error("Benchmark fixture requires version pagination.");
            const revision = createHash("sha256").update(JSON.stringify(index)).digest("hex");
            const current = {
              publisherBindingId,
              visibility: "public",
              archival: index["archival"],
              deprecation: index["deprecation"],
              revision,
              observedAt,
              validUntil: new Date(Date.parse(observedAt) + 30_000).toISOString(),
            };
            return item.knownRevision === revision
              ? { key: item.key, outcome: "unchanged", ...current }
              : {
                  key: item.key,
                  outcome: "metadata",
                  page: { ...current, versions: index["versions"], continuation: null },
                };
          });
          response.setHeader("cache-control", "private, no-store");
          send(
            200,
            JSON.stringify({ schemaVersion: 1, selectionPolicyVersion: "1", observedAt, results }),
            "application/json",
          );
        })
        .catch(() => sendProblem(500, "Fixture failure", "fixture_failure"));
      return;
    }
    if (method !== "GET" && method !== "HEAD") {
      sendProblem(405, "Method not allowed", "method_not_allowed");
      return;
    }
    if (segments.length < 5 || segments[0] !== "v1" || segments[1] !== "extensions") {
      sendProblem(404, "Not found", "not_found");
      return;
    }
    const owner = segments[2];
    const plural = segments[3];
    const name = segments[4];
    if (
      owner !== "@acme" ||
      (plural !== "skills" && plural !== "packs") ||
      name === undefined ||
      !/^bench-(?:\d{3}|pack-[ab])$/.test(name)
    ) {
      sendProblem(404, "Not found", "not_found");
      return;
    }
    const directory = path.join(fixtureRoot, "extensions", owner, plural, name);
    const indexPath = path.join(directory, "index.json");
    if (!fs.existsSync(indexPath)) {
      sendProblem(404, "Not found", "not_found");
      return;
    }
    try {
      const index = indexBody(indexPath);
      if (segments.length === 5) {
        if (failNextMetadata.delete(name)) {
          sendProblem(503, "Temporary fixture failure", "service_unavailable");
          return;
        }
        send(200, JSON.stringify(index), "application/json");
        return;
      }
      const version = segments[5];
      if (version === undefined || !/^\d+\.\d+\.\d+$/.test(version)) {
        sendProblem(404, "Not found", "not_found");
        return;
      }
      if (segments.length === 7 && segments[6] === "archive") {
        const archivePath = path.join(directory, `${version}.zip`);
        if (!fs.existsSync(archivePath)) {
          sendProblem(404, "Not found", "not_found");
          return;
        }
        send(200, fs.readFileSync(archivePath), "application/zip", true);
        return;
      }
      if (segments.length === 6 && isRecord(index) && Array.isArray(index["versions"])) {
        const selected = index["versions"].find(
          (entry: unknown) => isRecord(entry) && entry["version"] === version,
        );
        if (isRecord(selected)) {
          send(
            200,
            JSON.stringify({
              name,
              owner,
              type: plural === "skills" ? "skill" : "pack",
              version,
              published: selected["published"],
              integrity: selected["integrity"],
              yanked_at: selected["yanked_at"],
              visibility: "public",
            }),
            "application/json",
          );
          return;
        }
      }
      sendProblem(404, "Not found", "not_found");
    } catch {
      sendProblem(500, "Fixture failure", "fixture_failure");
    }
  });
  await new Promise<void>((resolve, reject) => {
    server.once("error", reject);
    server.listen(0, "127.0.0.1", resolve);
  });
  const address = server.address();
  if (address === null || typeof address === "string") {
    throw new Error("Could not determine benchmark Registry address.");
  }
  return {
    url: `http://127.0.0.1:${address.port}`,
    reset: (record) => {
      recording = record;
      records = [];
      activeArchiveBodies = 0;
      peakActiveArchiveBodies = 0;
    },
    failNextMetadata: (name) => {
      failNextMetadata.add(name);
    },
    metrics: () => {
      if (!recording) return null;
      const keys = new Set(records.map((record) => record.key));
      const latestStatuses = new Map<string, number>();
      let retryAttempts = 0;
      for (const record of records) {
        const key = record.key;
        const previous = latestStatuses.get(key);
        if (previous !== undefined && (previous === 408 || previous === 429 || previous >= 500)) {
          retryAttempts += 1;
        }
        latestStatuses.set(key, record.status);
      }
      return {
        requests: records.length,
        uniqueKeys: keys.size,
        repeatedKeys: records.length - keys.size,
        retryAttempts,
        archiveBodies: records.filter((record) => record.archiveBody).length,
        archiveBytes: records
          .filter((record) => record.archiveBody)
          .reduce((bytes, record) => bytes + record.responseBytes, 0),
        peakActiveArchiveBodies,
        byStatus: Object.fromEntries(
          [...new Set(records.map((record) => record.status))].map((status) => [
            String(status),
            records.filter((record) => record.status === status).length,
          ]),
        ),
      };
    },
    close: () =>
      new Promise<void>((resolve, reject) =>
        server.close((error) => (error ? reject(error) : resolve())),
      ),
  };
};
