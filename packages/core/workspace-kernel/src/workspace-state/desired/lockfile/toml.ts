/**
 * Canonical `axm.lock` TOML text.
 *
 * The emitter writes the stored document whole, in one canonical layout:
 * fixed table and key order, code-point-sorted keys and records, basic
 * strings only, and `\n` line endings. Identical stored content produces
 * identical bytes on every machine. A general TOML serializer offers no
 * control over inline versus standard tables or key order, so the layout is
 * owned here.
 *
 * @experimental This API is unstable and may change without notice.
 */

import { parse } from "smol-toml";
import { compareCodePoints } from "./compare-code-points.js";
import { PROJECTION_KINDS } from "./projections.js";
import type { StoredLockfileDocument } from "./schema.js";

/** Where the published JSON Schema for the lockfile's data model lives. */
const LOCKFILE_SCHEMA_URL = "https://axm.sh/schemas/axm-lock.schema.json";

const HEADER = [
  `#:schema ${LOCKFILE_SCHEMA_URL}`,
  "# Generated by axm; do not edit by hand. See: axm help workspace-state",
] as const;

// -----------------------------------------------------------------------------
// Parsing
// -----------------------------------------------------------------------------

/**
 * Plain data from parsed TOML: tables become ordinary objects. Dates stay as
 * the parser's `Date` subclass; AXM's own fields refuse them and `[tool.*]`
 * tables carry them through.
 */
const plain = (value: unknown): unknown => {
  if (Array.isArray(value)) return value.map(plain);
  if (value instanceof Date) return value;
  if (typeof value === "object" && value !== null)
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, plain(item)]));
  return value;
};

/** Parse lockfile text into plain data. Throws the TOML parser's error on invalid syntax. */
export const parseLockfileToml = (raw: string): unknown => plain(parse(raw));

// -----------------------------------------------------------------------------
// Scalars and keys
// -----------------------------------------------------------------------------

const SHORT_ESCAPES: Readonly<Record<string, string>> = {
  "\\": "\\\\",
  '"': '\\"',
  "\b": "\\b",
  "\t": "\\t",
  "\n": "\\n",
  "\f": "\\f",
  "\r": "\\r",
};

/** A TOML basic string. */
const basicString = (value: string): string => {
  let out = '"';
  for (const character of value) {
    const short = SHORT_ESCAPES[character];
    const code = character.codePointAt(0) ?? 0;
    out +=
      short ??
      (code < 0x20 || code === 0x7f ? `\\u${code.toString(16).padStart(4, "0")}` : character);
  }
  return `${out}"`;
};

const tomlKey = (key: string): string => (/^[A-Za-z0-9_-]+$/u.test(key) ? key : basicString(key));

const isTable = (value: unknown): value is Readonly<Record<string, unknown>> =>
  typeof value === "object" && value !== null && !Array.isArray(value) && !(value instanceof Date);

/** A scalar in AXM's own tables: strings, safe integers, and booleans only. */
const scalar = (value: unknown): string => {
  if (typeof value === "string") return basicString(value);
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "number" && Number.isSafeInteger(value)) return String(value);
  throw new Error("Lockfile values must be strings, integers, booleans, arrays, or tables");
};

/** A TOML float literal; `nan` and the infinities have their own spellings. */
const floatText = (value: number): string => {
  if (Number.isNaN(value)) return "nan";
  if (value === Infinity) return "inf";
  if (value === -Infinity) return "-inf";
  const text = String(value);
  return /[.e]/u.test(text) ? text : `${text}.0`;
};

/**
 * A scalar under `[tool.*]`: every TOML scalar kind, written from its parsed
 * value. A date is the parser's `Date` subclass, whose ISO form is its TOML
 * spelling, so a local date or time keeps its kind.
 */
const toolScalar = (value: unknown): string => {
  if (typeof value === "number" && !Number.isSafeInteger(value)) return floatText(value);
  if (value instanceof Date) return value.toISOString();
  return scalar(value);
};

// -----------------------------------------------------------------------------
// Composite values
// -----------------------------------------------------------------------------

type Rendered = ReadonlyArray<readonly [string, string]>;

const inlineTable = (fields: Rendered): string =>
  fields.length === 0
    ? "{}"
    : `{ ${fields.map(([key, value]) => `${tomlKey(key)} = ${value}`).join(", ")} }`;

/** Multi-line array: one element per line, two-space indent, trailing commas. */
const multilineArray = (items: ReadonlyArray<string>, indent: string): string =>
  items.length === 0
    ? "[]"
    : `[\n${items.map((item) => `${indent}  ${item},`).join("\n")}\n${indent}]`;

/**
 * The fields of `value` in `order`, skipping absent ones. A key outside the
 * order is an encoder defect: the emitter never drops data silently.
 */
const ordered = (
  value: unknown,
  order: ReadonlyArray<string>,
): ReadonlyArray<readonly [string, unknown]> => {
  if (!isTable(value)) throw new Error("Expected a lockfile table");
  const unknownKey = Object.keys(value).find((key) => !order.includes(key));
  if (unknownKey !== undefined) throw new Error(`Unexpected lockfile key "${unknownKey}"`);
  return order.flatMap((key) => {
    const item = value[key];
    return item === undefined ? [] : [[key, item] as const];
  });
};

const scalarTable = (value: unknown, order: ReadonlyArray<string>): string =>
  inlineTable(ordered(value, order).map(([key, item]) => [key, scalar(item)]));

/** Total emitter for `[tool.*]` values: keys sorted, nested tables inline. */
const generic = (value: unknown, indent: string): string => {
  if (Array.isArray(value)) {
    const items = value.map((item) => generic(item, `${indent}  `));
    return value.some(isTable)
      ? multilineArray(items, indent)
      : items.length === 0
        ? "[]"
        : `[${items.join(", ")}]`;
  }
  if (isTable(value))
    return inlineTable(
      Object.keys(value)
        .sort(compareCodePoints)
        .flatMap((key) => {
          const item = value[key];
          return item === undefined ? [] : [[key, generic(item, indent)] as const];
        }),
    );
  return toolScalar(value);
};

// -----------------------------------------------------------------------------
// Lockfile structures
// -----------------------------------------------------------------------------

const sourceOrder = (source: unknown): ReadonlyArray<string> => {
  if (!isTable(source)) throw new Error("Expected a package source table");
  if ("registry" in source) return ["registry"];
  if ("git" in source) return ["git", "path", "format"];
  if ("http" in source) return ["http", "kind", "entry", "path", "portable", "format"];
  return ["path", "format"];
};

const artifact = (value: unknown, indent: string): string =>
  inlineTable(
    ordered(value, ["format", "url", "digest", "files"]).map(([key, item]) => [
      key,
      key === "files"
        ? Array.isArray(item)
          ? multilineArray(
              item.map((file) => scalarTable(file, ["path", "url", "digest"])),
              indent,
            )
          : scalar(item)
        : scalar(item),
    ]),
  );

const dependencies = (value: unknown, indent: string): string => {
  if (!Array.isArray(value)) throw new Error("Expected Pack dependencies to be an array");
  const sorted = [...value].sort((left, right) =>
    compareCodePoints(
      isTable(left) ? String(left["name"]) : "",
      isTable(right) ? String(right["name"]) : "",
    ),
  );
  return multilineArray(
    sorted.map((dependency) => scalarTable(dependency, ["name", "range", "registry"])),
    indent,
  );
};

const PACKAGE_ORDER = [
  "id",
  "source",
  "version",
  "archive",
  "publisher",
  "commit",
  "git-tree",
  "artifact",
  "tree",
  "manifest-version",
  "manifest-identity",
  "source-root",
  "dependencies",
] as const;

const packageLines = (record: unknown): ReadonlyArray<string> =>
  ordered(record, PACKAGE_ORDER).map(([key, value]) => {
    const rendered =
      key === "source"
        ? scalarTable(value, sourceOrder(value))
        : key === "artifact"
          ? artifact(value, "")
          : key === "dependencies"
            ? dependencies(value, "")
            : scalar(value);
    return `${tomlKey(key)} = ${rendered}`;
  });

const component = (value: unknown): string =>
  inlineTable(
    ordered(value, ["format", "root", "path", "manifest", "marketplace"]).map(([key, item]) => [
      key,
      key === "marketplace" ? scalarTable(item, ["path", "name"]) : scalar(item),
    ]),
  );

const bindingFields = (binding: unknown): Rendered =>
  ordered(binding, ["package", "name", "spec", "component"]).map(([key, item]) => [
    key,
    key === "component" ? component(item) : scalar(item),
  ]);

const sortedKeys = (table: Readonly<Record<string, unknown>>): ReadonlyArray<string> =>
  Object.keys(table).sort(compareCodePoints);

const BINDING_TABLE_NAMES = ["subagents", "rules", "hooks", "knowledge", "packs"] as const;

/** Emit a stored lockfile document as canonical `axm.lock` text. */
export const emitLockfileToml = (document: StoredLockfileDocument): string => {
  const lines: Array<string> = [...HEADER, `version = ${scalar(document.version)}`];
  const header = (name: string) => lines.push("", name);

  const bindingTable = (name: string, table: Readonly<Record<string, unknown>> | undefined) => {
    if (table === undefined || Object.keys(table).length === 0) return;
    header(`[${name}]`);
    for (const alias of sortedKeys(table))
      lines.push(`${tomlKey(alias)} = ${inlineTable(bindingFields(table[alias]))}`);
  };

  const packages = [...(document.package ?? [])].sort((left, right) =>
    compareCodePoints(left.id, right.id),
  );
  for (const record of packages) {
    header("[[package]]");
    lines.push(...packageLines(record));
  }

  bindingTable("skills", document.skills);

  const mcp = [...(document.mcp ?? [])].sort(
    (left, right) =>
      compareCodePoints(left.package, right.package) || compareCodePoints(left.name, right.name),
  );
  for (const binding of mcp) {
    header("[[mcp]]");
    for (const [key, value] of bindingFields(binding)) lines.push(`${tomlKey(key)} = ${value}`);
  }

  for (const name of BINDING_TABLE_NAMES) bindingTable(name, document[name]);

  for (const kind of PROJECTION_KINDS) {
    const state = document.projections?.[kind];
    if (state === undefined) continue;
    header(`[projections.${kind}]`);
    lines.push(`contract = ${scalar(state.contract)}`);
    header(`[projections.${kind}.units]`);
    for (const path of sortedKeys(state.units))
      lines.push(`${tomlKey(path)} = ${scalarTable(state.units[path], ["gen", "output"])}`);
  }

  const tool = document.tool ?? {};
  for (const name of sortedKeys(tool)) {
    const table = tool[name] ?? {};
    header(`[tool.${tomlKey(name)}]`);
    for (const key of sortedKeys(table)) lines.push(`${tomlKey(key)} = ${generic(table[key], "")}`);
  }

  return `${lines.join("\n")}\n`;
};
